#!/usr/bin/env python
'''
TetherLRS: writes platformio-tetherlrs.ini, one [env:tx-<name>] for every ESP [env:rx-<name>] in platformio.ini
    python tools/tetherlrs_tx_envs.py [--check]
Each Tx env builds the receiver's own hal as the ground radio (TLRS_RX_AS_TX in Common/hal/device_conf.h): the Rx's
sources filter with the Tx main instead of the Rx main, the Rx's build flags plus -D TLRS_RX_AS_TX.
Run it again after an mLRS update brings new receivers; --check only says whether the file is up to date (for CI).
'''
import configparser
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = os.path.join(ROOT, 'platformio.ini')
OUT = os.path.join(ROOT, 'platformio-tetherlrs.ini')
FAMILIES = ('esp82xx', 'esp32', 'esp32c3', 'esp32s3')


def load():
    cp = configparser.ConfigParser(interpolation=None, strict=False, comment_prefixes=(';',), inline_comment_prefixes=(';',))
    cp.optionxform = str
    with open(SRC, encoding='utf-8') as f:
        cp.read_file(f)
    return cp


def resolved(cp, section, option):
    # the value as PlatformIO sees it, following extends
    seen = set()
    while section and section not in seen:
        seen.add(section)
        if cp.has_option(section, option):
            return cp.get(section, option)
        section = cp.get(section, 'extends', fallback='').strip()
    return None


def family(cp, section):
    seen = set()
    while section and section not in seen:
        seen.add(section)
        name = section
        for fam in FAMILIES:
            if name == f'env_common_rx_{fam}':
                return fam
        section = cp.get(section, 'extends', fallback='').strip()
    return None


def lines(value):
    return [l.strip() for l in value.strip().splitlines() if l.strip()]


def generate():
    cp = load()
    out = ['; generated by tools/tetherlrs_tx_envs.py from the [env:rx-*] sections of platformio.ini, do not edit',
           '; every ESP receiver also as the ground radio: its own hal, TLRS_RX_AS_TX in Common/hal/device_conf.h', '']
    for section in cp.sections():
        if not section.startswith('env:rx-'):
            continue
        name = section[len('env:rx-'):]
        if any(s == f'env:tx-{name}' or s.startswith(f'env:tx-{name}-') for s in cp.sections()):  # mLRS has that Tx
            continue
        fam = family(cp, section)
        if fam is None:
            continue
        srcf = resolved(cp, section, 'build_src_filter')
        flags = resolved(cp, section, 'build_flags')
        if srcf is None or flags is None:
            continue
        srcf = srcf.replace(f'env_common_rx_{fam}.', f'env_common_tx_{fam}.')
        if f'env_common_tx_{fam}.' not in srcf:
            continue
        out.append(f'[env:tx-{name}]')
        out.append(f'extends = {section}')
        out.append('build_src_filter =')
        out += ['  ' + l for l in lines(srcf)]
        out.append('build_flags =')
        out += ['  ' + l for l in lines(flags)]
        out.append('  -D TLRS_RX_AS_TX')
        out.append('')
    return '\n'.join(out)


if __name__ == '__main__':
    text = generate()
    if '--check' in sys.argv:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current != text:
            print('platformio-tetherlrs.ini is out of date: run python tools/tetherlrs_tx_envs.py')
            sys.exit(1)
        print('platformio-tetherlrs.ini up to date')
    else:
        with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print(OUT, sum(l.startswith('[env:') for l in text.splitlines()), 'Tx envs')
